def pinned(path, sha):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != sha:
        raise ValueError(f"Evidence changed: {path}")
    return data


def array(values):
    return "{" + ",".join(map(str, values)) + "}"


def scene(path):
    root = ET.fromstring(pinned(path, SCENE_SHA))
    lines = ["/* Generated by export_five_profile.py; do not tune rigid bodies here. */",
             "static const Link links[FIVE_AXES] = {"]
    for body in root.findall(".//body[joint]"):
        inertia, joint = body.find("inertial"), body.find("joint")
        w,x,y,z = map(float, body.get("quat","1 0 0 0").split())
        k = 2/(w*w+x*x+y*y+z*z)
        rotation = [[1-k*(y*y+z*z), k*(x*y-w*z), k*(x*z+w*y)],
                    [k*(x*y+w*z), 1-k*(x*x+z*z), k*(y*z-w*x)],
                    [k*(x*z-w*y), k*(y*z+w*x), 1-k*(x*x+y*y)]]
        xx,yy,zz,xy,xz,yz = inertia.get("fullinertia").split()
        matrix = [[xx,xy,xz],[xy,yy,yz],[xz,yz,zz]]
        lines.append("    "+array([array(body.get("pos","0 0 0").split()),
            array(inertia.get("pos").split()), "{"+array(map(array,rotation))+"}",
            "{"+array(map(array,matrix))+"}",inertia.get("mass"),joint.get("armature")])+",")
    return "\n".join([*lines, "};", ""])


def merge(boxes):
    """Exact union: merge touching/overlapping intervals only if the other 3 axes match."""
    boxes = sorted(set(boxes))
    while True:
        before = len(boxes)
        for axis in range(4):
            groups = defaultdict(list)
            for b in boxes:
                groups[b[:axis]+b[axis+1:]].append(b[axis])
            boxes = []
            for key, intervals in groups.items():
                joins = []
                for lo,hi in sorted(intervals):
                    if joins and lo <= joins[-1][1]:
                        joins[-1] = (joins[-1][0], max(hi, joins[-1][1]))
                    else:
                        joins.append((lo,hi))
                boxes.extend(key[:axis]+(j,)+key[axis:] for j in joins)
        if len(boxes) == before:
            return sorted(boxes)


def workspace(build):
    lines = ["/* Generated: cells index pairs of binary64 endpoints, without rounding. */"]
    for m, hashes in zip(("baseline","alignment"),TABLE_SHA):
        base = json.loads(pinned(build/f"workspace_factored_regions_20261117_{m}_v10/factored_regions.json",hashes[0]))
        domain = base["admissibleSoftwareDomainDeg"]
        assert all(g["verifiedSoftwareBoxesDeg"] == [domain] for g in base["groups"][:-1])
        boxes = base["groups"][-1]["verifiedSoftwareBoxesDeg"]
        del base
        extra = json.loads(pinned(build/f"workspace_frontier_balanced_all_20261117_v1/{m}/gap_refinement.json",hashes[1]))
        boxes.extend(extra["verifiedSoftwareBoxesDeg"])
        # Complete focus windows can be used as single path cells; do not add unknown windows.
        for window in extra["windows"]:
            if window["refinement"]["unknownFraction"] == 0:
                boxes.append(window["focusSoftwareBoundsDeg"])
        assert all(b[0] == [0,0] and all(domain[i][0] <= lo <= hi <= domain[i][1]
                   for i,(lo,hi) in enumerate(b)) for b in boxes)
        boxes = merge(tuple(tuple(interval) for interval in b[1:]) for b in boxes)
        coords = sorted({x for b in boxes for pair in b for x in pair})
        index = {x:i for i,x in enumerate(coords)}
        pairs = sorted({pair for b in boxes for pair in b})
        refs = {pair:i for i,pair in enumerate(pairs)}
        assert max(len(coords),len(pairs)) <= 65536
        lines += [f"static const double {m}_coords[] = {{",
                  *[",".join(map(repr,coords[i:i+8]))+"," for i in range(0,len(coords),8)],"};",
                  f"static const Pair {m}_pairs[] = {{"]
        lines += [",".join(array([index[a],index[b]]) for a,b in pairs[i:i+8])+","
                  for i in range(0,len(pairs),8)]
        lines += ["};",
                  f"static const Cell {m}_cells[] = {{"]
        lines += [",".join("{"+array(refs[pair] for pair in b)+"}" for b in boxes[i:i+4])+","
                  for i in range(0,len(boxes),4)]
        lines += ["};"]
        print(m, len(boxes), "exact cells,", len(coords), "distinct endpoints")
    routes = json.loads(pinned(build/"workspace_support_paths_20261117_v2/nominal_paths.json",
                        "7375a26520b8a7e09f8cf5c806c4794f4dc5bcc0efbe5605d27c8cd641ca8f27"))
    tube = json.loads(pinned(build/"workspace_tracking_tube_20261117_v1/tracking_tube.json",
                        "e7cfaf005193b2298116d5480c45dd30e8e1f2109670cd9e16c4d3b7479bf257"))
    assert tube["continuousNominalTubeProven"] and tube["constraints"] == 89
    lines += ["static const double routes[][4][5] = {"]
    for row in routes["selectedRoutes"]:
        assert len(row["routeSoftwareDeg"]) == 4 and all(any(p["route"] == row["id"] and
            p["mapping"] == m and p["segment"] == n and p["result"]["status"] == "numerical_motion_bound_pass"
            for p in tube["proofs"]) for m in ("baseline","alignment") for n in range(3))
        lines.append(array(map(array,row["routeSoftwareDeg"]))+",")
    lines += ["};","static const double tube_deg[5] = "+array(tube["angularTubeDeg"])+";"]
    sl = json.loads(pinned(build/"workspace_support_query_20261117_v2/envelope_query.json",
                           "bd626f1219da0c0d862fe83fbb8522e14c4b699b76a838e2e0a28e666932bfe1"))
    assert len(sl["commonJ3IntervalsDeg"]) == 1
    lines += ["static const double slice_deg[5] = "+array(sl["softwareDeg"])+";",
              "static const double slice_j3[2] = "+array(sl["commonJ3IntervalsDeg"][0])+";"]
    return "\n".join(lines)+"\n"


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--scene",type=Path,required=True)
    p.add_argument("--build",type=Path,default=ROOT/"build")
    p.add_argument("--check",action="store_true",help="compare without modifying files")
    args = p.parse_args()
    for name,text in (("five_scene.inc",scene(args.scene)),("five_workspace.inc",workspace(args.build))):
        dest = ROOT/"config"/name
        if args.check:
            if dest.read_text(encoding="ascii") != text:
                raise SystemExit(f"Stale generated file: {dest}")
        else:
            dest.write_text(text,encoding="ascii",newline="\n")
